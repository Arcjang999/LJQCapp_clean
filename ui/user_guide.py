def render_frontline_user_guide() -> None:
    """Render the same concise help body in a dedicated page or another view."""
    st.caption('从顶部“帮助 → 使用说明”进入。按要做的操作展开步骤；首次使用先看“首次准备与资料维护”。')
    for group, sections in GUIDE_GROUPS:
        st.subheader(group)
        for title, content in sections:
            with st.expander(title):
                st.markdown(dedent(content).strip())
    st.info('首次使用时，先登记基础资料并确认项目和批次，再录入结果。遇到无法录入或生成报告的提示，请按页面说明补齐资料后重新核对。')


def render_user_guide_page() -> None:
    from ui.common import render_module_header

    if st.button('返回项目工作台', key='user_guide_home'):
        from ui.daily_navigation import return_to_project_workspace
        return_to_project_workspace()
    if st.session_state.get('user_guide_practical'):
        from pathlib import Path
        render_module_header('操作说明', caption='项目资料、结果录入与各页面核对步骤', tone='guide', eyebrow='操作帮助')
        guide = Path(__file__).resolve().parents[1] / 'docs' / 'OPERATION_GUIDE.md'
        if guide.is_file():
            body = guide.read_text(encoding='utf-8')
            if body.startswith('# 操作说明\n'):
                body = body.split('\n', 1)[1].lstrip()
            st.markdown(body)
        else:
            st.info('操作说明尚未准备完成，请先查看使用说明。')
        return
    render_module_header('使用说明', caption='资料准备与管理、项目配置、日常录入、异常处理和报告备份', tone='guide', eyebrow='操作帮助')
    render_frontline_user_guide()
